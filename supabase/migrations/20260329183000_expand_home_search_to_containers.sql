create or replace function public.search_entities_by_embedding(
  query_embedding_text text,
  filter_tenant_id bigint,
  entity_types text[] default array['item', 'container']::text[],
  show_deleted boolean default false,
  page_limit integer default 20,
  page_offset integer default 0,
  similarity_threshold double precision default 0.25
)
returns table (
  entity_type text,
  entity_id bigint,
  similarity double precision,
  match_source text,
  total_count bigint
)
language sql
stable
security definer
set search_path = public, tenant, extensions, pg_temp
as $$
with query_vector as (
  select query_embedding_text::extensions.vector(1024) as embedding
),
raw_matches as (
  select
    d.entity_type,
    d.entity_id,
    d.source_type,
    1 - (d.embedding <=> q.embedding) as similarity,
    row_number() over (
      partition by d.entity_type, d.entity_id
      order by
        1 - (d.embedding <=> q.embedding) desc,
        case when d.source_type = 'image' then 0 else 1 end,
        d.updated_at desc
    ) as rn
  from public.entity_search_documents d
  cross join query_vector q
  where
    filter_tenant_id is not null
    and filter_tenant_id = any(tenant.user_tenant_ids())
    and d.tenant_id = filter_tenant_id
    and d.entity_type = any(entity_types)
),
best_matches as (
  select
    entity_type,
    entity_id,
    source_type as match_source,
    similarity
  from raw_matches
  where rn = 1 and similarity >= similarity_threshold
),
filtered_entities as (
  select
    'item'::text as entity_type,
    i.id as entity_id,
    i.created_at,
    bm.similarity,
    bm.match_source
  from public.items i
  join best_matches bm
    on bm.entity_type = 'item'
    and bm.entity_id = i.id
  where
    (filter_tenant_id = any(tenant.user_tenant_ids()) and i.tenant_id = filter_tenant_id)
    and case when show_deleted then i.deleted_at is not null else i.deleted_at is null end

  union all

  select
    'container'::text as entity_type,
    c.id as entity_id,
    c.created_at,
    bm.similarity,
    bm.match_source
  from public.containers c
  join best_matches bm
    on bm.entity_type = 'container'
    and bm.entity_id = c.id
  where
    (filter_tenant_id = any(tenant.user_tenant_ids()) and c.tenant_id = filter_tenant_id)
    and case when show_deleted then c.deleted_at is not null else c.deleted_at is null end
),
filtered_count as (
  select count(*)::bigint as total_count from filtered_entities
),
paged_entities as (
  select *
  from filtered_entities
  order by similarity desc, created_at desc
  offset page_offset
  limit page_limit
)
select
  p.entity_type,
  p.entity_id,
  p.similarity,
  p.match_source,
  fc.total_count
from paged_entities p
cross join filtered_count fc;
$$;

